"""Dockerfile contract: do not chown node_modules for runtime npm installs.

The container points ``HERMES_TUI_DIR`` at the prebuilt TUI bundle, so the TUI
launcher must skip the ``_tui_need_npm_install`` path. Runtime npm install
writability is therefore the wrong fix: it hides the regression and adds a slow
recursive chown over large dependency trees.
"""
from __future__ import annotations

from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[2]
DOCKERFILE = REPO_ROOT / "Dockerfile"


def _dockerfile_instructions(text: str) -> list[str]:
    instructions: list[str] = []
    current = ""

    for raw_line in text.splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue

        continued = line.removesuffix("\\").strip()
        current = f"{current} {continued}".strip()
        if not line.endswith("\\"):
            instructions.append(current)
            current = ""

    return instructions


def test_dockerfile_uses_prebuilt_tui_bundle() -> None:
    instructions = _dockerfile_instructions(DOCKERFILE.read_text())

    assert "ENV HERMES_TUI_DIR=/opt/hermes/ui-tui" in instructions, (
        "Docker image must point the launcher at the prebuilt TUI bundle so "
        "it does not enter the runtime npm install path."
    )

